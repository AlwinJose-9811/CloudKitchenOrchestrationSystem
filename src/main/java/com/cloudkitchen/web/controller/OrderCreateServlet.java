package com.cloudkitchen.web.controller;

import com.cloudkitchen.domain.MenuItem;
import com.cloudkitchen.domain.enums.OrderSource;
import com.cloudkitchen.domain.enums.PaymentMode;
import com.cloudkitchen.dto.BrandOption;
import com.cloudkitchen.dto.OrderItemRequest;
import com.cloudkitchen.dto.OrderRequest;
import com.cloudkitchen.dto.SubmissionResult;
import com.cloudkitchen.exception.CloudKitchenException;
import com.cloudkitchen.web.support.BadRequestException;
import com.cloudkitchen.web.support.BaseServlet;
import com.cloudkitchen.web.support.FormInput;
import com.cloudkitchen.web.support.Views;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.servlet.http.HttpSession;
import java.io.IOException;
import java.io.Serializable;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * {@code GET} and {@code POST /orders/new} (SDD 10.2 routes 8 and 9, FR-ORD-08, any signed-in role): manual entry of an
 * <em>in-house</em> order. The source is always {@code IN_HOUSE} and the reference is generated by the domain; neither is read
 * from the request, and prices never are: the service looks them up. The page works in two steps without scripts: choosing
 * a brand ({@code GET ?brandCode=}) shows that brand's active items. The submission goes through
 * {@code OrderService.submitOrder}, the same path as every other source, so validation, the stock deduction and the queue
 * rules are the ones of the pipeline. Whatever the outcome the answer is a redirect; a refusal keeps what the user typed in
 * the session (consumed by the next {@code GET}) so the form is shown again filled in, with the reasons.
 *
 * <p>The item ids and quantities arrive as two parallel lists. They are written by the page, so lists of different length or an
 * id that is not a number are a 400; a quantity is typed by a person, so text that is not a whole number is shown as an error.
 */
public class OrderCreateServlet extends BaseServlet {

    private static final long serialVersionUID = 1L;
    private static final Logger LOG = LoggerFactory.getLogger(OrderCreateServlet.class);
    private static final String RETAINED = "ck.orderForm";
    private static final int MAX_LINES = 100;

    /** What a refused submission keeps for the next page: plain text only, nothing but what the user typed and the reasons. */
    private static final class Retained implements Serializable {
        private static final long serialVersionUID = 1L;
        final String brandCode;
        final String customerName;
        final String deliveryDistanceKm;
        final String paymentMode;
        final Map<String, String> quantities;
        final List<String> problems;

        Retained(String brandCode, String customerName, String deliveryDistanceKm, String paymentMode, Map<String, String> quantities, List<String> problems) {
            this.brandCode = brandCode;
            this.customerName = customerName;
            this.deliveryDistanceKm = deliveryDistanceKm;
            this.paymentMode = paymentMode;
            this.quantities = quantities;
            this.problems = problems;
        }
    }

    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response) throws ServletException, IOException {
        HttpSession session = request.getSession(true);
        Retained retained = session.getAttribute(RETAINED) instanceof Retained r ? r : null;
        session.removeAttribute(RETAINED);
        try {
            List<BrandOption> brands = services().menu().activeBrands();
            String wanted = request.getParameter("brandCode");
            if (wanted == null || wanted.isBlank()) {
                wanted = retained == null ? null : retained.brandCode;
            }
            String brand = null;
            for (BrandOption option : brands) {
                if (option.code().equals(wanted == null ? null : wanted.strip())) {
                    brand = option.code();
                }
            }
            List<MenuItem> menu = brand == null ? List.of() : services().menu().activeForStation(brand);
            List<Map<String, Object>> lines = new ArrayList<>();
            for (MenuItem item : menu) {
                Map<String, Object> line = new LinkedHashMap<>();
                line.put("itemId", item.getId());
                line.put("name", item.getName());
                line.put("price", item.getPrice().toPlainString());
                line.put("quantity", retained == null || !brand.equals(retained.brandCode) ? "0" : retained.quantities.getOrDefault(Long.toString(item.getId()), "0"));
                lines.add(line);
            }
            request.setAttribute("brands", Views.of(brands));
            request.setAttribute("brand", brand);
            request.setAttribute("lines", Views.of(lines));
            request.setAttribute("modes", List.of(PaymentMode.CASH.name(), PaymentMode.UPI.name(), PaymentMode.CARD.name()));
            request.setAttribute("form", retained == null ? Map.of() : Map.of("customerName", retained.customerName,
                    "deliveryDistanceKm", retained.deliveryDistanceKm, "paymentMode", retained.paymentMode));
            request.setAttribute("problems", retained == null ? List.of() : retained.problems);
        } catch (CloudKitchenException e) {
            throw new ServletException("The menu could not be read (" + e.getCode() + ")", e);
        }
        request.setAttribute("pageTitle", "New order");
        render(request, response, "orders/new");
    }

    @Override
    protected void doPost(HttpServletRequest request, HttpServletResponse response) throws ServletException, IOException {
        String[] ids = request.getParameterValues("itemId");
        String[] quantities = request.getParameterValues("quantity");
        int count = ids == null ? 0 : ids.length;
        if (count != (quantities == null ? 0 : quantities.length) || count > MAX_LINES) {
            throw new BadRequestException("itemId");
        }
        String brandCode = trimmed(request.getParameter("brandCode"));
        String customer = request.getParameter("customerName") == null ? "" : request.getParameter("customerName").strip();
        String distanceText = trimmed(request.getParameter("deliveryDistanceKm"));
        String modeText = trimmed(request.getParameter("paymentMode"));

        List<String> problems = new ArrayList<>();
        Map<String, String> typed = new LinkedHashMap<>();
        List<OrderItemRequest> lines = new ArrayList<>();
        for (int i = 0; i < count; i++) {
            long itemId = parseItemId(ids[i]);
            String quantityText = trimmed(quantities[i]);
            typed.put(Long.toString(itemId), quantityText);
            Integer quantity = quantityText.isEmpty() ? Integer.valueOf(0) : FormInput.wholeNumber(quantityText);
            if (quantity == null || quantity < 0) {
                problems.add("The quantity of item " + itemId + " must be a whole number, 0 or more.");
            } else if (quantity > 0) {
                lines.add(new OrderItemRequest(itemId, quantity));
            }
        }
        BigDecimal distance = FormInput.decimal(distanceText);
        PaymentMode mode = parseMode(modeText);

        if (problems.isEmpty()) {
            OrderRequest order = new OrderRequest(OrderSource.IN_HOUSE, null, brandCode, customer, distance, mode, lines);
            SubmissionResult result = services().orders().submitOrder(order);
            if (finish(request, response, result)) {
                return;
            }
            if (result.outcome() == SubmissionResult.Outcome.REJECTED) {
                result.errors().forEach(error -> problems.add(error.message()));
                if (result.errors().isEmpty()) {
                    problems.add(rejectionText(result.reasonCode()));
                }
            }
        }
        flashError(request, problems.size() == 1 ? problems.get(0) : "The order was not placed: " + problems.size() + " problems.");
        request.getSession(true).setAttribute(RETAINED, new Retained(brandCode, customer, distanceText, modeText, typed, new ArrayList<>(problems)));
        redirect(request, response, "/orders/new");
    }

    /** Answers the outcomes that end at an order; {@code true} when the response has been sent. */
    private boolean finish(HttpServletRequest request, HttpServletResponse response, SubmissionResult result) throws IOException {
        switch (result.outcome()) {
            case ACCEPTED -> {
                LOG.info("In-house order {} entered by user {}", result.orderId(), currentUser(request).userId());
                flashSuccess(request, "Order " + result.orderId() + " was accepted and queued for its kitchen.");
                redirect(request, response, "/orders/view?id=" + result.orderId());
                return true;
            }
            case QUEUE_FULL -> {
                flashError(request, result.compensated()
                        ? "The kitchen queue is full, so the order was not accepted: it is marked FAILED and its stock was given back."
                        : "The kitchen queue is full. The order is marked FAILED, but giving its stock back is still pending; the system keeps retrying.");
                redirect(request, response, "/orders/view?id=" + result.orderId());
                return true;
            }
            case INDETERMINATE -> {
                flashError(request, "The order was created but its state could not be settled. Check it before entering it again.");
                redirect(request, response, "/orders/view?id=" + result.orderId());
                return true;
            }
            case DUPLICATE -> {
                if (result.orderId() != null) {
                    flashInfo(request, "This order already exists.");
                    redirect(request, response, "/orders/view?id=" + result.orderId());
                    return true;
                }
                flashInfo(request, "The same order is being processed right now; check the order list before entering it again.");
                redirect(request, response, "/orders");
                return true;
            }
            default -> {
                return false;
            }
        }
    }

    private static String rejectionText(String reason) {
        if (SubmissionResult.INSUFFICIENT_STOCK.equals(reason)) {
            return "There is not enough stock for this order.";
        }
        if (SubmissionResult.STARTING_UP.equals(reason) || SubmissionResult.SHUTTING_DOWN.equals(reason)) {
            return "The system is not accepting orders right now (starting up or shutting down). Try again shortly.";
        }
        return "The order could not be placed right now. Nothing was changed; try again.";
    }

    private static long parseItemId(String text) {
        try {
            return Long.parseLong(text.strip());
        } catch (NumberFormatException e) {
            throw new BadRequestException("itemId");
        }
    }

    private static PaymentMode parseMode(String text) {
        try {
            return text.isEmpty() ? null : PaymentMode.valueOf(text);
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    private static String trimmed(String text) {
        return text == null ? "" : text.strip();
    }
}
